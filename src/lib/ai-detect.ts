// Detect profile text that claims AI-generated work or that the person isn't the
// real creator. UGCOrigin is human-only; such profiles get flagged (and warned),
// and can be shadowbanned. Keep the list tight to avoid false positives.
const AI_PHRASES: RegExp[] = [
  /\bai[-\s]?ugc\b/,
  /\bai[-\s]?generated\b/,
  /\bgenerated by ai\b/,
  /\bai[-\s]?avatar(s)?\b/,
  /\bai[-\s]?content\b/,
  /\bai[-\s]?created\b/,
  /\bai[-\s]?influencer\b/,
  /\bsynthetic (video|content|media)\b/,
  /\bdeepfake(s)?\b/,
  /\bfaceless ai\b/,
  /\bnot (me|myself) in the (video|content|clip)\b/,
];

export function detectAiClaim(text: string | null | undefined): boolean {
  if (!text) return false;
  const t = text.toLowerCase();
  return AI_PHRASES.some((re) => re.test(t));
}
